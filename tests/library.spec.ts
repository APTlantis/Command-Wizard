import { expect, test } from "@playwright/test";
import { readFile } from "node:fs/promises";

test("Library creates, filters, edits, duplicates, exports and deletes exact multiline commands", async ({ page }, info) => {
  await page.goto("/");
  await page.getByRole("button", { name: "Library", exact: true }).click();
  await expect(page.getByPlaceholder("Search tools...")).toHaveCount(0);
  await page.getByRole("button", { name: "New Command", exact: true }).click();
  const command = "  first --argument " + "long-value ".repeat(60) + "\nsecond\n";
  await page.getByLabel("Title", { exact: true }).fill("My multiline command");
  await page.getByLabel("Command", { exact: true }).fill(command);
  await page.getByLabel("Notes", { exact: true }).fill("Reusable operation");
  await page.getByLabel("Tags (comma-separated)").fill("work, linux");
  await page.getByLabel("Saved command category").selectOption("linux");
  await page.getByRole("button", { name: "Save Command", exact: true }).click();
  await expect(page.getByLabel("Command", { exact: true })).toHaveValue(command);
  await page.getByLabel("Wrap long lines").uncheck();
  await expect(page.getByLabel("Command", { exact: true })).toHaveAttribute("wrap", "off");
  await page.getByLabel("Filter category").selectOption("powershell");
  await expect(page.getByText("No saved commands match.", { exact: false })).toBeVisible();
  await page.getByLabel("Filter category").selectOption("linux");
  await page.getByLabel("Search saved commands").fill("Reusable");
  await expect(page.getByRole("button", { name: /My multiline command Unassigned/ })).toBeVisible();
  await page.getByLabel("Search saved commands").fill("");
  await page.getByLabel("Filter tags").selectOption("work");
  await page.getByLabel("Title", { exact: true }).fill("Unsaved title");
  page.once("dialog", (dialog) => dialog.dismiss());
  await page.getByRole("button", { name: "New Command", exact: true }).click();
  await expect(page.getByLabel("Title", { exact: true })).toHaveValue("Unsaved title");
  page.once("dialog", (dialog) => dialog.accept());
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(page.getByLabel("Title", { exact: true })).toHaveValue("My multiline command");
  await page.getByRole("button", { name: "Duplicate", exact: true }).click();
  await page.getByRole("button", { name: "Save Command", exact: true }).click();
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export JSON", exact: true }).click();
  const saved = JSON.parse(await readFile(await (await download).path() as string, "utf8"));
  expect(saved).toHaveLength(2);
  expect(saved.map((entry: {command: string}) => entry.command)).toEqual([command, command]);
  expect(saved[0].id).not.toBe(saved[1].id);
  await page.screenshot({ path: `artifacts/verification/library-${info.project.name}.png` });
  page.once("dialog", (dialog) => dialog.accept());
  await page.getByRole("button", { name: "Delete Command", exact: true }).click();
  await expect(page.getByText("Most recently updated · 1 commands")).toBeVisible();
});

test("grouped commands save a reviewed snapshot and restore it after installed schema changes", async ({ page }, info) => {
  await page.goto("/");
  for (const name of ["dotnet build", "dotnet publish"]) {
    await page.getByRole("button", { name: "Import", exact: true }).click();
    await page.getByPlaceholder("winget", { exact: true }).fill(name);
    await page.getByRole("textbox", { name: "Pasted Help Text" }).fill(`Usage: ${name} [project] [OPTIONS]\nOptions:\n  --no-restore  Skip restore`);
    await page.getByRole("button", { name: "Parse Paste", exact: true }).click();
    await page.getByRole("button", { name: "Save Schema", exact: true }).click();
  }
  await expect(page.locator("summary", { hasText: "dotnet (2)" })).toBeVisible();
  await page.getByPlaceholder("Search tools...").fill("dotnet build");
  await expect(page.locator("summary")).toHaveCount(0);
  await page.getByRole("button", { name: /dotnet build/ }).click();
  await page.getByPlaceholder("Search tools...").fill("");
  await page.getByTestId("builder-parameters").locator("input").fill("demo.csproj");
  await page.getByRole("button", { name: "Save to Library", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Save to Library", exact: true });
  await expect(dialog.getByLabel("Command", { exact: true })).toHaveValue("dotnet build demo.csproj");
  await dialog.getByLabel("Title", { exact: true }).fill("Build my project");
  await dialog.getByRole("button", { name: "Save Command", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByTestId("builder-parameters").locator("input")).toHaveValue("demo.csproj");
  await page.getByRole("button", { name: "Schema", exact: true }).click();
  await page.getByLabel("Fixed Command Prefix").fill("publish");
  await page.getByRole("button", { name: "Save Schema", exact: true }).click();
  await page.getByRole("button", { name: "Library", exact: true }).click();
  await page.getByRole("button", { name: /Build my project dotnet build/ }).click();
  await expect(page.getByText("Builder snapshot", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Reopen in Builder", exact: true }).click();
  await expect(page.getByText("dotnet build demo.csproj", { exact: true })).toBeVisible();
  await expect(page.getByText("Saved Builder snapshot · select an installed command to leave this snapshot.", { exact: true })).toBeVisible();
  await page.screenshot({ path: `artifacts/verification/snapshot-${info.project.name}.png` });
  await page.getByRole("button", { name: "View in Library", exact: true }).click();
  await page.getByLabel("Command", { exact: true }).fill("dotnet build changed.csproj");
  await expect(page.getByText("Text command", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Reopen in Builder", exact: true })).toHaveCount(0);
});
